export function toTerraform(
  nodes: FlowNode[],
  edges: Edge[],
  sim: Sim,
): string {
  const services = nodes.filter((n) => !isEdgeOnly(n.kind));
  if (!services.length) return "# nothing to build — add some components first\n";

  const nameOf = new Map(nodes.map((n) => [n.id, svcName(n, nodes)]));
  const out: string[] = [
    "# Generated by Flow Studio — http://localhost:3000",
    `# ${nodes.length} components · ${edges.length} links`,
    "",
    'terraform {',
    '  required_providers {',
    '    aws = { source = "hashicorp/aws", version = "~> 5.0" }',
    "  }",
    "}",
    "",
    'provider "aws" { region = var.region }',
    "",
    'variable "region" { default = "us-east-1" }',
    "",
    "# ── resources ──",
    "",
  ];

  for (const n of services) {
    const map = TF[n.kind];
    const sn = sim.nodes[n.id];
    const cap = sn?.capacity ?? CATALOG[n.kind].capacity;
    const count = cap === Infinity ? 1 : instanceCount(n.kind, cap);
    const name = nameOf.get(n.id)!.replace(/-/g, "_");
    if (!map) {
      out.push(`# ${shortName(n.kind)} (${name}) — no direct AWS equivalent modelled`);
      out.push("");
      continue;
    }
    out.push(`resource "${map.resource}" "${name}" {`);
    for (const a of map.attrs) out.push(`  ${a}`);
    if (count > 1)
      out.push(`  # scales to ~${count} instances at current load (${Math.round(cap).toLocaleString()} rps)`);
    out.push(`  tags = { Name = "${name}" }`);
    out.push("}");
    out.push("");
  }

  out.push("# ── wiring ──");
  for (const e of edges) {
    const a = nameOf.get(e.from);
    const b = nameOf.get(e.to);
    if (a && b) out.push(`# ${a} --${e.mode}--> ${b}`);
  }
  return out.join("\n");
}

/** convenience: what capacity we'd provision for a node, for docs/exports */
export const capacityFor = (kind: NodeKind, inflow: number) =>
  provisionCapacity(kind, inflow);
