function svcName(n: FlowNode, nodes: FlowNode[]) {
  const sameKind = nodes.filter((x) => x.kind === n.kind);
  const idx = sameKind.findIndex((x) => x.id === n.id);
  const base = n.kind.replace(/[^a-z0-9]/gi, "-");
  return sameKind.length > 1 ? `${base}-${idx + 1}` : base;
}

export function toDockerCompose(
  nodes: FlowNode[],
  edges: Edge[],
  sim: Sim,
): string {
  const services = nodes.filter((n) => !isEdgeOnly(n.kind));
  if (!services.length) return "# nothing to run — add some components first\n";

  const nameOf = new Map(nodes.map((n) => [n.id, svcName(n, nodes)]));
  const lines: string[] = [
    "# Generated by Flow Studio — http://localhost:3000",
    `# ${nodes.length} components · ${edges.length} links`,
    "services:",
  ];

  for (const n of services) {
    const entry = CATALOG[n.kind];
    const sn = sim.nodes[n.id];
    const image = IMAGES[n.kind] ?? "alpine:latest";
    const cap = sn?.capacity ?? entry.capacity;
    const count = cap === Infinity ? 1 : instanceCount(n.kind, cap);
    const name = nameOf.get(n.id)!;
    lines.push(`  ${name}:`);
    lines.push(`    image: ${image}`);
    lines.push(`    # ${shortName(n.kind)} · ${entry.tagline}`);
    if (count > 1) lines.push(`    deploy:`);
    if (count > 1) lines.push(`      replicas: ${count}`);
    const down = edges
      .filter((e) => e.from === n.id)
      .map((e) => nameOf.get(e.to))
      .filter(Boolean) as string[];
    if (down.length) {
      lines.push(`    depends_on:`);
      for (const d of Array.from(new Set(down))) lines.push(`      - ${d}`);
    }
    if (n.kind === "database" || n.kind === "replica" || n.kind === "shard") {
      lines.push(`    environment:`);
      lines.push(`      POSTGRES_PASSWORD: \${DB_PASSWORD:-changeme}`);
    }
    if (n.kind === "gpu" || n.kind === "model") {
      lines.push(`    deploy:`);
      lines.push(`      resources:`);
      lines.push(`        reservations:`);
      lines.push(`          devices:`);
      lines.push(`            - capabilities: [gpu]`);
    }
    lines.push("");
  }

  lines.push("# internal network so services resolve each other by name");
  lines.push("networks:");
  lines.push("  default:");
  lines.push("    driver: bridge");
  return lines.join("\n");
}

