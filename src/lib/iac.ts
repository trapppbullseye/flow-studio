/** how many catalog-sized instances the current design provisions */
function instanceCount(kind: NodeKind, capacity: number) {
  return Math.max(1, Math.round(instancedUnits(kind, capacity)));
}

const isEdgeOnly = (k: NodeKind) =>
  k === "client" || k === "browser" || k === "mobile" || k === "iot";

